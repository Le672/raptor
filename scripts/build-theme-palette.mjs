// Rebuild the portal's literal-color overrides when its styles change. Native
// media/readers use their existing dark palettes; artwork and map tiles remain assets.
import postcss from 'postcss';
import { readFile, writeFile, readdir } from 'node:fs/promises';
const prefix = 'html[data-yukino-theme="dark"] .site-refresh';
const files = [];
async function scan(dir) { for (const entry of await readdir(dir, { withFileTypes: true })) { const path = `${dir}/${entry.name}`; if (entry.isDirectory()) await scan(path); else if (path.endsWith('.css') && !path.endsWith('/desktop.css')) files.push(path); } }
await scan('src'); files.sort();
function mapped(hex, property) {
  const raw = hex.slice(1), full = raw.length <= 4 ? [...raw].map(c => c + c).join('') : raw;
  if (![6, 8].includes(full.length)) return hex;
  const rgb = [0, 2, 4].map(i => parseInt(full.slice(i, i + 2), 16) / 255), alpha = full.slice(6);
  const max = Math.max(...rgb), min = Math.min(...rgb), light = (max + min) / 2, saturation = max === min ? 0 : (max - min) / (1 - Math.abs(2 * light - 1));
  if (property === 'color' || property === 'fill' || property === 'stroke') {
    if (light > .86 && saturation < .15) return hex; // White labels on solid buttons.
    if (saturation < .2) return (light < .38 ? '#dce6f1' : '#acbdd0') + alpha;
    return '#' + rgb.map(channel => Math.round((channel * .38 + .62) * 255).toString(16).padStart(2, '0')).join('') + alpha;
  }
  if (property.includes('border') || property.includes('outline')) return light > .48 ? '#43566e' + alpha : hex;
  if (light < .65) return hex; // Keep solid accents and game pieces.
  const base = [29, 41, 56];
  return '#' + rgb.map((channel, i) => Math.round(base[i] + (channel - .9) * 45).toString(16).padStart(2, '0')).join('') + alpha;
}
const output = ['/* Generated by scripts/build-theme-palette.mjs from the portal styles. */'];
for (const file of files) {
  const ast = postcss.parse(await readFile(file, 'utf8'));
  ast.walkRules(rule => {
    if (rule.parent.type === 'atrule' && /keyframes/.test(rule.parent.name)) return;
    const declarations = [];
    rule.each(node => {
      if (node.type !== 'decl' || !/^(?:color|background(?:-color|-image)?|border(?:-.+)?|outline(?:-color)?|fill|stroke)$/.test(node.prop)) return;
      const next = node.value.replace(/#[a-f0-9]{3,8}\b/gi, value => mapped(value, node.prop));
      if (next !== node.value) declarations.push(`${node.prop}:${next}${node.important ? '!important' : ''}`);
    });
    if (!declarations.length) return;
    const selectors = rule.selectors.filter(selector => !/^(?::root|html\b|body\b|#root\b)/.test(selector)).map(selector =>
      selector.includes('.site-refresh') ? selector.replace(/\.site-refresh\b/, 'html[data-yukino-theme="dark"] .site-refresh')
        : selector.includes('.site-shell') ? selector.replace(/\.site-shell\b/, prefix) : prefix + ' ' + selector);
    if (!selectors.length) return;
    let text = selectors.join(',') + '{' + declarations.join(';') + '}';
    let parent = rule.parent;
    while (parent?.type === 'atrule') { if (['media', 'supports', 'container'].includes(parent.name)) text = `@${parent.name} ${parent.params}{${text}}`; parent = parent.parent; }
    output.push(text);
  });
}
await writeFile('shared/theme/portal-dark.css', output.join('\n') + '\n');
console.log(`Prepared ${output.length - 1} scoped portal color rules.`);
