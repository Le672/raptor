import { build } from 'vite';
import { fileURLToPath } from 'node:url';
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
await build({ configFile: fileURLToPath(new URL('../novel/vite.config.ts', import.meta.url)) });
const root = new URL('../novel/dist/', import.meta.url), html = await readFile(new URL('index.html', root), 'utf8');
const assets = [...new Set(Array.from(html.matchAll(/(?:src|href)="(\/assets\/[^"?#]+)"/g), match => match[1]))];
if (!assets.some(path => path.endsWith('.js')) || !assets.some(path => path.endsWith('.css'))) throw new Error('Novel application assets are missing');
const worker = await readFile(new URL('sw.js', root), 'utf8'), manifest = await readFile(new URL('manifest.webmanifest', root), 'utf8');
const icons = ['/icons/icon-192.png', '/icons/icon-512.png', '/icons/maskable-512.png', '/icons/apple-touch-icon.png'];
const hashInput = createHash('sha256').update(html).update(worker).update(manifest);
for (const icon of icons) hashInput.update(await readFile(new URL(icon.slice(1), root)));
const hash = hashInput.digest('hex').slice(0, 12);
await writeFile(new URL('index.html', root), html.replace('</head>', `<meta name="novel-app-version" content="${hash}"/></head>`));
const sw = worker.replace('yukino-novel-shell-v1', `yukino-novel-shell-${hash}`);
await writeFile(new URL('sw.js', root), `self.__NOVEL_PRECACHE = ${JSON.stringify(['/', '/book.svg', '/manifest.webmanifest', ...icons, ...assets])};\n${sw}`);
console.log(`Verified offline shell: ${assets.length} versioned JS/CSS assets.`);
